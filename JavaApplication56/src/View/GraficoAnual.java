    public int ano() {
        LocalDate hoje = LocalDate.now();
        int ano = 0;
        String[] opcoes = {"Ano Atual"};
        JComboBox<String> comboBox = new JComboBox<>(opcoes);
        int result = JOptionPane.showConfirmDialog(null, comboBox, "Mostrar Gráfico Referente a Qual Ano?", JOptionPane.OK_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (result == JOptionPane.OK_OPTION) {
            String escolha = (String) comboBox.getSelectedItem();
            if (escolha.equals("Ano Atual")) {
                ano = hoje.getYear();
            } else {
                String stringAno = JOptionPane.showInputDialog(null, "Digite o Ano para Gerar o Gráfico!");
                ano = Integer.parseInt(stringAno);
            }
        } else if (result == JOptionPane.CANCEL_OPTION || result == JOptionPane.CLOSED_OPTION) {
            JOptionPane.showMessageDialog(null, "Operação cancelada. Permanecendo na tela atual.");

            return -1;

        }

        return ano;
    }

    public void graficoCarro(JPanel painel, int ano) {
        ListaCarros carros = new ListaCarros();
        List<Integer> nCarros = carros.listaPorAno(ano);

        List<String> meses = new ArrayList<>();
        String[] nomeMeses = {"JAN", "FEV", "MAR", "ABR", "MAI", "JUN", "JUL", "AGO", "SET", "OUT", "NOV", "DEZ"};

        for (int i = 0; i < 12; i++) {
            meses.add(nomeMeses[i]);

        }

        CategoryChart chart = new CategoryChartBuilder()
                .width(800).height(600).title("Carros ao logo do ano").xAxisTitle("Meses").yAxisTitle("Número de Carros").build();
        chart.addSeries("Carros", meses, nCarros);
        XChartPanel<CategoryChart> chartPanel = new XChartPanel<>(chart);
        painel.add(chartPanel, BorderLayout.CENTER);
    }

    public void graficoLucro(JPanel painel, int ano) {
        ListaLucro lucro = new ListaLucro();
        List<Double> lucroMensal = lucro.listaPorAno(ano);

        List<String> meses = new ArrayList<>();
        String[] nomeMeses = {"JAN", "FEV", "MAR", "ABR", "MAI", "JUN", "JUL", "AGO", "SET", "OUT", "NOV", "DEZ"};

        for (int i = 0; i < 12; i++) {
            meses.add(nomeMeses[i]);

        }

        CategoryChart chart = new CategoryChartBuilder()
                .width(800).height(600).title("Lucro ao logo do ano").xAxisTitle("Meses").yAxisTitle("Valores em (R$)").build();
        chart.addSeries("Lucros", meses, lucroMensal);
        XChartPanel<CategoryChart> chartPanel = new XChartPanel<>(chart);
        painel.add(chartPanel, BorderLayout.CENTER);
    }

